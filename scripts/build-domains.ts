// Bundle the public suffix parser for Chrome, which cannot resolve npm packages.
const result=await Bun.build({entrypoints:['node_modules/tldts/dist/es6/index.js'],target:'browser',minify:true});
if(!result.success)throw new Error('Domain parser build failed');
await Bun.write('extension/domain.js','// Generated by bun run scripts/build-domains.ts. tldts: MIT, see domain-LICENSE.\n'+await result.outputs[0].text());
await Bun.write('extension/domain-LICENSE',Bun.file('node_modules/tldts/LICENSE'));
